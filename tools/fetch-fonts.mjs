// Downloads every Google Fonts stylesheet listed in brand/identities.json,
// saves the woff2 files under fonts/ and writes fonts/fonts.css with local URLs.
// Usage: node tools/fetch-fonts.mjs
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'fonts');
// A modern browser UA makes Google serve woff2 split by unicode-range subsets.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const data = JSON.parse(await readFile(path.join(root, 'brand/identities.json'), 'utf8'));
const cssUrls = [...new Set(data.identities.map(i => i.typography.google_fonts_css))];

// 1. Collect @font-face rules. Variable fonts reuse one file for several weights.
const faces = [];
const remotes = new Map(); // remote url -> { family, style, subset, weights:Set }
for (const cssUrl of cssUrls) {
  const css = await (await fetch(cssUrl, { headers: { 'User-Agent': UA } })).text();
  for (const [, subset, block] of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]*})/g)) {
    const family = block.match(/font-family:\s*'([^']+)'/)[1];
    const style = block.match(/font-style:\s*(\w+)/)[1];
    const weight = block.match(/font-weight:\s*(\d+)/)[1];
    const remote = block.match(/url\((https:[^)]+)\)/)[1];
    if (!remotes.has(remote)) remotes.set(remote, { family, style, subset, weights: new Set() });
    remotes.get(remote).weights.add(weight);
    faces.push({ subset, block, remote });
  }
}

// 2. Download each file once, named after everything it covers.
await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
const local = new Map();
for (const [remote, f] of remotes) {
  const weights = [...f.weights].sort().join('-');
  const name = `${f.family.toLowerCase().replace(/\s+/g, '-')}-${f.style}-${weights}-${f.subset}.woff2`;
  await writeFile(path.join(outDir, name), Buffer.from(await (await fetch(remote)).arrayBuffer()));
  local.set(remote, name);
}

// 3. Write the stylesheet, dropping rules repeated across stylesheets (Nunito Sans).
const rules = [...new Set(faces.map(f => `/* ${f.subset} */\n${f.block.replace(f.remote, local.get(f.remote))}`))];
const header = '/* Self-hosted copies of the Google Fonts stylesheets in brand/identities.json.\n   Generated by tools/fetch-fonts.mjs, do not edit by hand. */\n';
await writeFile(path.join(outDir, 'fonts.css'), header + rules.join('\n') + '\n');
console.log(`${cssUrls.length} stylesheets, ${rules.length} @font-face rules, ${local.size} woff2 files`);
